# -*- coding: utf-8 -*-
"""Synthetic-data generation and ML surrogate models for the antenna model.

Important: AI targets are labels generated by antenna_core.calculate_antenna.
Metrics therefore measure how well ML reproduces that analytical approximation,
not agreement with a measurement or a full-wave EM solver.
"""
from __future__ import annotations

from typing import Any

import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.model_selection import train_test_split
from sklearn.neural_network import MLPRegressor
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler

from antenna_core import MATERIALS, calculate_antenna

FEATURE_COLUMNS = [
    "radius_cm", "freq_mhz", "wire_radius_mm", "n_turns", "rho_ohm_m"
]
TARGET_COLUMNS = ["Rr_ohm", "Zin_real_ohm", "Zin_imag_ohm", "gain_dBi_approx"]
LOG_TARGETS = {"Rr_ohm", "Zin_real_ohm", "Zin_imag_ohm"}


def generate_synthetic_dataset(n_samples: int = 3000, random_state: int = 42) -> pd.DataFrame:
    """Create reproducible synthetic samples inside a practical small-loop domain."""
    if n_samples < 200:
        raise ValueError("Cần ít nhất 200 mẫu để chia tập huấn luyện/kiểm tra có ý nghĩa.")
    rng = np.random.default_rng(random_state)
    material_names = list(MATERIALS.keys())
    material_rhos = np.array([float(MATERIALS[name]["rho_ohm_m"]) for name in material_names])
    rows: list[dict[str, Any]] = []

    # R=0.8..8 cm and f=5..50 MHz keep C/lambda below 0.1 at the upper corner.
    for _ in range(n_samples):
        radius = float(rng.uniform(0.8, 8.0))
        freq = float(rng.uniform(5.0, 50.0))
        wire = float(rng.uniform(0.25, 1.50))
        turns = int(rng.integers(1, 5))
        mat_idx = int(rng.integers(0, len(material_names)))
        material = material_names[mat_idx]
        try:
            result = calculate_antenna(radius, freq, wire, turns, 50.0, material)
        except ValueError:
            continue
        row = {
            "radius_cm": radius,
            "freq_mhz": freq,
            "wire_radius_mm": wire,
            "n_turns": turns,
            "material": material,
            "rho_ohm_m": material_rhos[mat_idx],
            "C_over_lambda": result["circumference_lambda"],
            "Rr_ohm": result["Rr_ohm"],
            "Zin_real_ohm": result["Zin_real_ohm"],
            "Zin_imag_ohm": result["Zin_imag_ohm"],
            "gain_dBi_approx": result["gain_dBi_approx"],
            "radiation_efficiency_pct": result["radiation_efficiency_pct"],
        }
        rows.append(row)

    dataset = pd.DataFrame(rows)
    if len(dataset) < 0.95 * n_samples:
        raise RuntimeError("Không tạo đủ dữ liệu hợp lệ; hãy thử lại với random_state khác.")
    return dataset


def _transform_target(values: np.ndarray, target_name: str) -> np.ndarray:
    values = np.asarray(values, dtype=float)
    if target_name in LOG_TARGETS:
        return np.log10(np.maximum(values, 1e-30))
    return values


def _inverse_target(values: np.ndarray, target_name: str) -> np.ndarray:
    values = np.asarray(values, dtype=float)
    if target_name in LOG_TARGETS:
        return np.power(10.0, values)
    return values


def train_models(
    dataset: pd.DataFrame,
    model_name: str = "Random Forest",
    random_state: int = 42,
) -> dict[str, Any]:
    """Train one estimator per target and evaluate on a held-out test set."""
    if model_name not in {"Random Forest", "ANN"}:
        raise ValueError("model_name phải là 'Random Forest' hoặc 'ANN'.")
    if len(dataset) < 200:
        raise ValueError("Dataset quá nhỏ; cần tối thiểu 200 mẫu.")

    x = dataset[FEATURE_COLUMNS].astype(float).to_numpy()
    y_raw = dataset[TARGET_COLUMNS].astype(float).to_numpy()
    indices = np.arange(len(dataset))
    train_idx, test_idx = train_test_split(
        indices, test_size=0.20, random_state=random_state
    )
    x_train, x_test = x[train_idx], x[test_idx]
    y_train_raw, y_test_raw = y_raw[train_idx], y_raw[test_idx]

    fitted_models: dict[str, Any] = {}
    metric_rows: list[dict[str, Any]] = []
    predictions: dict[str, np.ndarray] = {}

    for col_idx, target in enumerate(TARGET_COLUMNS):
        y_train = _transform_target(y_train_raw[:, col_idx], target)
        if model_name == "Random Forest":
            estimator = RandomForestRegressor(
                n_estimators=180,
                max_depth=None,
                min_samples_leaf=2,
                max_features=1.0,
                n_jobs=-1,
                random_state=random_state,
            )
        else:
            estimator = Pipeline([
                ("scale", StandardScaler()),
                ("ann", MLPRegressor(
                    hidden_layer_sizes=(64, 32),
                    activation="relu",
                    solver="adam",
                    alpha=0.001,
                    learning_rate_init=0.002,
                    max_iter=350,
                    early_stopping=True,
                    validation_fraction=0.12,
                    n_iter_no_change=22,
                    random_state=random_state,
                )),
            ])
        estimator.fit(x_train, y_train)
        pred_transformed = estimator.predict(x_test)
        pred = _inverse_target(pred_transformed, target)
        pred = np.maximum(pred, 0.0) if target in LOG_TARGETS else pred
        actual = y_test_raw[:, col_idx]
        mae = float(mean_absolute_error(actual, pred))
        rmse = float(np.sqrt(mean_squared_error(actual, pred)))
        r2 = float(r2_score(actual, pred))
        metric_rows.append({
            "Đại lượng": target,
            "MAE": mae,
            "RMSE": rmse,
            "R²": r2,
        })
        fitted_models[target] = estimator
        predictions[target] = pred

    metrics = pd.DataFrame(metric_rows)
    actual_frame = pd.DataFrame(y_test_raw, columns=TARGET_COLUMNS)
    prediction_frame = pd.DataFrame(predictions)
    return {
        "model_name": model_name,
        "models": fitted_models,
        "metrics": metrics,
        "actual_test": actual_frame,
        "prediction_test": prediction_frame,
        "n_train": len(train_idx),
        "n_test": len(test_idx),
        "feature_columns": FEATURE_COLUMNS,
        "target_columns": TARGET_COLUMNS,
        "random_state": random_state,
    }


def predict_one(bundle: dict[str, Any], values: dict[str, float]) -> dict[str, float]:
    """Predict all targets for one geometry/material setting."""
    x = np.array([[
        float(values["radius_cm"]),
        float(values["freq_mhz"]),
        float(values["wire_radius_mm"]),
        float(values["n_turns"]),
        float(values["rho_ohm_m"]),
    ]], dtype=float)
    output: dict[str, float] = {}
    for target in TARGET_COLUMNS:
        prediction_t = np.asarray(bundle["models"][target].predict(x), dtype=float).reshape(-1)
        prediction = float(_inverse_target(prediction_t[0], target))
        if target in LOG_TARGETS:
            prediction = max(0.0, prediction)
        output[target] = prediction
    return output
